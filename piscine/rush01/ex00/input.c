int	check_input(int argc, char **argv)
{
	int		i;
	char	a;

	i = 0;
	if (argc != 2)
		return (0);
	while (i < 31)
	{
		a = argv[1][i];
		if (i % 2 == 0 && !(a >= '1' && a <= '4'))
			return (0);
		if (i % 2 == 1 && a != ' ')
			return (0);
		i++;
	}
	if (argv[1][31] != '\0')
		return (0);
	return (1);
}
